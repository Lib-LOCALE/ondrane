//! Build script: generates the Figma icon registry and compiles the Slint UI.
//!
//! Every icon variant of the Figma "Icon" component set lives in
//! `ui/assets/icons` as `<name>.svg` (neutral layer) and optionally
//! `<name>.accent.svg` (accent-coloured layer of two-tone/active variants).
//! They are exposed to Slint as `Icons.<name>` (`IconData { base, accent }`).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn ident(stem: &str) -> String {
    let mut out = String::new();
    for c in stem.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
        } else {
            out.push('_');
        }
    }
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, 'i');
    }
    out
}

fn generate_icons(icon_dir: &Path, out_file: &Path, lookup_file: &Path) {
    let mut icons: BTreeMap<String, (Option<PathBuf>, Option<PathBuf>)> = BTreeMap::new();
    for entry in std::fs::read_dir(icon_dir).expect("ui/assets/icons missing") {
        let path = entry.unwrap().path();
        let name = path.file_name().unwrap().to_string_lossy().to_string();
        let Some(stem) = name.strip_suffix(".svg") else {
            continue;
        };
        let abs = path.canonicalize().unwrap();
        if let Some(base) = stem.strip_suffix(".accent") {
            icons.entry(ident(base)).or_default().1 = Some(abs);
        } else {
            icons.entry(ident(stem)).or_default().0 = Some(abs);
        }
    }

    let mut s = String::from(
        "// @generated by build.rs from ui/assets/icons - do not edit.\n\
         export struct IconData { base: image, accent: image }\n\
         export global Icons {\n",
    );
    let url = |p: &PathBuf| format!("@image-url(\"{}\")", p.to_string_lossy().replace('\\', "/"));
    for (name, (base, accent)) in &icons {
        let mut fields = Vec::new();
        if let Some(b) = base {
            fields.push(format!("base: {}", url(b)));
        }
        if let Some(a) = accent {
            fields.push(format!("accent: {}", url(a)));
        }
        writeln!(
            s,
            "    out property <IconData> {}: {{ {} }};",
            name,
            fields.join(", ")
        )
        .unwrap();
    }
    s.push_str("}\n");
    std::fs::write(out_file, s).unwrap();

    // Rust-side lookup by Figma icon name, used for data-driven menus/toolbars.
    let mut r = String::from(
        "// @generated by build.rs\n\
         /// Figma icon variant by name (\"forward-10-sec\", \"PiP\", ...).\n\
         pub fn icon_by_name(icons: &Icons<'_>, name: &str) -> IconData {\n\
         \x20   let key: String = name.chars().map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_lowercase() } else { '_' }).collect();\n\
         \x20   match key.as_str() {\n",
    );
    for name in icons.keys() {
        writeln!(r, "        \"{0}\" => icons.get_{0}(),", name).unwrap();
    }
    r.push_str("        _ => IconData::default(),\n    }\n}\n");
    std::fs::write(lookup_file, r).unwrap();
}

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let icon_dir = manifest.join("ui/assets/icons");
    println!("cargo:rerun-if-changed=ui");
    println!("cargo:rerun-if-changed=lang");

    let generated = out_dir.join("generated");
    std::fs::create_dir_all(&generated).unwrap();
    generate_icons(
        &icon_dir,
        &generated.join("icons.slint"),
        &out_dir.join("icon_lookup.rs"),
    );

    let config = slint_build::CompilerConfiguration::new()
        .with_include_paths(vec![generated])
        .with_style("fluent-dark".into())
        // French (and future) translations: lang/<code>/LC_MESSAGES/ondrane.po,
        // shared with the Rust strings (src/i18n.rs), hence no per-component context.
        .with_bundled_translations(manifest.join("lang"))
        .with_default_translation_context(slint_build::DefaultTranslationContext::None);
    slint_build::compile_with_config("ui/main.slint", config).expect("Slint UI compilation failed");

    // Embed the application icon in ondrane.exe: Explorer, the Start menu
    // and desktop shortcuts and "Apps & features" all read `ondrane.exe,0`.
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        let ico = manifest.join("../packaging/windows/ondrane.ico");
        println!("cargo:rerun-if-changed={}", ico.display());
        let mut res = winresource::WindowsResource::new();
        res.set_icon(&ico.to_string_lossy())
            .set("ProductName", "Ondrane")
            .set("FileDescription", "Ondrane");
        if let Err(e) = res.compile() {
            println!("cargo:warning=could not embed the Windows icon: {e}");
        }
    }
}
